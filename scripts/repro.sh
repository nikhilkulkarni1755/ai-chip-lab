#!/usr/bin/env bash
# repro.sh (stage 50_repro) - rerun Tasks 1 and 3 from a clean output directory with the pinned images and
# compare with the first (official) run -> results/repro_report.json (identical/different per check).
# Task 2 is NOT re-run a third time: pnr's t2_summary.json already holds a two-run-from-clean determinism
# verdict (same image digest and core count); it is reused.
#   scripts/repro.sh [--dry]
#   env: REPRO_NCASES (default 10000, must equal the first run)
#        REPRO_T1_AFTER  epoch: the first Task 1 run must have finished after this time (default 0)
#        REPRO_T1_DEADLINE epoch: give up waiting for the first Task 1 run then (exit 5, nothing started; default none)
# Order: Task 3 (one fresh pass, T3_PASSES=1) -> wait for the first Task 1 run to be finished (.done, no .running, no
# t1_run container, summary newer than REPRO_T1_AFTER) -> Task 1 rerun (full) -> compare.
# No heavy lock (it only serializes ORFS; lab-sim jobs are light, rule 4); one job at a time, niced.
# Provenance: git tree SHAs of the input directories are recorded before and after each rerun (.cache/repro_run/inputs_*.json)
# and compared with the time of the first run, so first run and rerun are shown to use the same inputs.
# Run from the main checkout. Do not edit this file while it runs.
set -u
LAB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$LAB" || exit 2
source ./env.sh >/dev/null 2>&1
RUN=".cache/repro_run"
N="${REPRO_NCASES:-10000}"
S=results/.stages
say() { echo "$(date +%H:%M:%S) repro: $*" | tee -a logs/run.log; }
T1_PATHS="rtl tb formal eqy scripts/t1_run.sh scripts/t1_summary.py scripts/t1_waveform.py docker/requirements.lock"
T3_PATHS="model arch scripts/t3_run.sh docker/requirements.lock"
snap() {  # snap <name> <paths...>  -> $RUN/inputs_<name>.json
  local name="$1"; shift
  python3 - "$RUN/inputs_$name.json" "$@" <<'PY'
import json, subprocess, sys, time
out, paths = sys.argv[1], sys.argv[2:]
def git(*a): return subprocess.run(["git"] + list(a), capture_output=True, text=True).stdout.strip()
d = {"time": time.strftime("%F %T"), "head": git("rev-parse", "HEAD"), "paths": {}}
for p in paths:
    d["paths"][p] = {"git_object_sha": git("rev-parse", "HEAD:" + p), "uncommitted_changes": bool(git("status", "--porcelain", "--", p)),
                     "last_commit_epoch": int(git("log", "-1", "--format=%ct", "--", p) or 0)}
json.dump(d, open(out, "w"), indent=1, sort_keys=True)
PY
}
if [ "${1:-}" = "--dry" ]; then
  echo "would run: nice env T3_PASSES=1 T3_PLOTS=0 T3_SUMMARY=$RUN/t3_summary.json scripts/t3_run.sh $RUN/t3"
  echo "would wait for first Task 1 run, then: nice scripts/t1_run.sh $N $RUN/t1"
  echo "would run: python3 scripts/repro_compare.py --lab $LAB --run $RUN"
  exit 0
fi
{ [ -f "$S/30_arch_model.done" ] || [ -f "$S/30_arch_model.failed" ]; } && [ -f results/t3_summary.json ] && [ -d results/t3 ] \
  || { echo "first run of 30_arch_model not finished"; exit 4; }
rm -rf "$RUN"; mkdir -p "$RUN" logs/50_repro; rm -f "$S/50_repro.done" "$S/50_repro.failed"; : > "$S/50_repro.running"
say "started (N=$N)"

# ---- Task 3: one fresh pass
snap t3_start $T3_PATHS
nice -n 10 env T3_PASSES=1 T3_PLOTS=0 T3_SUMMARY="$RUN/t3_summary.json" bash scripts/t3_run.sh "$RUN/t3" > logs/50_repro/t3.log 2>&1; say "t3 rerun rc=$?"
snap t3_end $T3_PATHS

# ---- wait for the first Task 1 run to be final
AFTER="${REPRO_T1_AFTER:-0}"; DEADLINE="${REPRO_T1_DEADLINE:-0}"
t1_final() {
  [ -f "$S/10_rtl_verify.done" ] && [ ! -f "$S/10_rtl_verify.running" ] && [ -f results/t1_summary.json ] || return 1
  docker ps --format '{{.Command}}' 2>/dev/null | grep -q "t1_run" && return 1
  local m; m=$(stat -f %m results/t1_summary.json); [ "$m" -gt "$AFTER" ] || return 1
  return 0
}
say "waiting for the first Task 1 run to finish (summary newer than epoch $AFTER)"
until t1_final; do
  if [ "$DEADLINE" -gt 0 ] && [ "$(date +%s)" -gt "$DEADLINE" ]; then say "deadline passed while waiting for the first Task 1 run; Task 1 repro NOT started"; exit 5; fi
  sleep 30
done
sleep 20; t1_final || { say "first Task 1 run changed state again; restarting wait"; until t1_final; do sleep 30; done; }
say "first Task 1 run is final; starting Task 1 rerun (N=$N)"
snap t1_start $T1_PATHS
nice -n 10 bash scripts/t1_run.sh "$N" "$RUN/t1" > logs/50_repro/t1.log 2>&1; say "t1 rerun rc=$?"
snap t1_end $T1_PATHS

python3 scripts/repro_compare.py --lab "$LAB" --run "$RUN" | tee logs/50_repro/compare.log; rc=${PIPESTATUS[0]}
rm -f "$S/50_repro.running"
if [ -f results/repro_report.json ]; then
  echo "report written; pass=$(python3 -c "import json;print(json.load(open('results/repro_report.json'))['pass'])")" > "$S/50_repro.done"
else
  { echo "repro_report.json not produced"; tail -50 logs/50_repro/compare.log; } > "$S/50_repro.failed"
fi
say "finished compare rc=$rc"
exit $rc
